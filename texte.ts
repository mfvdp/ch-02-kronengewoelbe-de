    // Merkzeichen für den Neustart nach dem Spielende. Der Endbildschirm setzt es direkt vor control.reset(). Der
    // nächste Start liest es, löscht es sofort und geht dann ohne Vorspann zum Titelbild. Nach dem Aus- und Einschalten
    // fehlt es, dann läuft der Vorspann wieder.
    export const neustart_merker = "neustart-titel"
    // Wahr, wenn dieser Start ein Neustart nach dem Spielende ist.
    export let direkt_zum_titel = false
    export function text(nr: TextNr): string {
        return texte[nr]
    }
    export function formatiere(nr: TextNr, erste_zahl: number, zweite_zahl: number = 0): string {
        let ergebnis = text(nr)
        let stelle = ergebnis.indexOf("{0}")
        if (stelle >= 0) ergebnis = ergebnis.substr(0, stelle) + erste_zahl + ergebnis.substr(stelle + 3)
        stelle = ergebnis.indexOf("{1}")
        if (stelle >= 0) ergebnis = ergebnis.substr(0, stelle) + zweite_zahl + ergebnis.substr(stelle + 3)
        return ergebnis
    }
    // Beim Start: Ist das Merkzeichen neustart_merker gesetzt, geht das Spiel direkt zum Titelbild. Das Merkzeichen
    // gilt nur für diesen einen Start und wird sofort gelöscht. Danach kommen die Menüs dazu.
    export function richte_ein(): void {
        direkt_zum_titel = settings.exists(neustart_merker)
        if (direkt_zum_titel) settings.remove(neustart_merker)
        pause(100)
        installiere_menues()
    }
